def _w(s, width=7.0, color="", weight=1.0, pause_after=0.0, fill=False):
    return stroke_from_path_commands(s, width=width, color=color,
                                     weight=weight, pause_after=pause_after,
                                     fill=fill, tol=0.6)


def _glyph(*strokes) -> StrokeAsset:
    return StrokeAsset(strokes=list(strokes), viewBox=(100, 120))


