"""Single-line handwriting glyphs: letters/digits/punctuation as ordered strokes.

Each glyph is authored as centerline strokes in a 100-unit em box (baseline
at y=80, x-height 40, cap height 62, descender to y=100). Strokes draw in
reading order with pen lifts between them. This is a limited alphabet; a
missing glyph is a validation error with a disclosed typed-text fallback,
never a silent omission.
"""
