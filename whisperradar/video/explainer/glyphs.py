def has_glyph(ch: str) -> bool:
    return ch in _ALPHABET


SUPPORTED = "".join(sorted(_ALPHABET))


def missing_glyphs(text: str) -> list:
    return [c for c in text if c != "\n" and not c.isspace() and c not in _ALPHABET]


def text_strokes(text: str, origin, scale: float, color: str = ""):
    """-> (strokes, (advance_w_px, height_px)). Glyphs placed left-to-right
    from origin, scaled; newline wraps a line (line height 1.5 em).
    Marker width derives from the glyph scale - this is NOT a wrap width;
    wrapping/sizing is the caller's job (see pipe._handwriting_strokes)."""
    strokes = []
    x, y = origin
    line_h = 120 * scale * 0.72
    width = 6.5 * scale
    max_x = x
    for ch in text:
        if ch == "\n":
            x = origin[0]
            y += line_h
            continue
        if ch.isspace():
            x += (SPACE_ADVANCE if ch != "\t" else SPACE_ADVANCE * 4) * scale
            continue
        glyph = _ALPHABET.get(ch)
        if glyph is None:
            raise ValueError(f"no handwriting glyph for {ch!r}")
        for s in glyph.strokes:
            pts = [(x + px * scale, y + (py - 18) * scale) for px, py in s.points]
            strokes.append(Stroke(points=pts, width=width,
                                  color=color or s.color, fill=False,
                                  weight=s.weight * max(0.35, s.length / 120.0),
                                  pause_after=s.pause_after * 0.4))
        x += ADVANCE * scale
        max_x = max(max_x, x)
    return strokes, (max_x - origin[0], (y - origin[1]) + 120 * scale)


def glyph_asset(ch: str) -> StrokeAsset:
    return _ALPHABET[ch]
