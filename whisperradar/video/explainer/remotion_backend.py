"""Optional Remotion backend: renders ONE scene to a silent clip.

It sits at the same boundary as the pen renderer (`prepare.render_scene_clip`),
so timing, subtitles, joining, audio and Stop/resume stay in Python. A scene
opts in by carrying a `remotion` block: {"component": name, "params": {...}}.

  * Components are an allowlist (COMPONENTS); each validates its own
    parameters. Nothing generated by a model is ever executed as React.
  * Clips cache under out/remotion/, never next to the pen renderer's clips,
    keyed by content: component, params, frames, fps, size, theme and a hash of
    the node project's sources and lockfile.
  * Stop: the process runs in its own group; on cancel it gets SIGTERM
    (Remotion cancels cleanly), then is killed after a grace period. Only the
    owned process tree is touched.
  * Needs Node and `npm ci` in tools/remotion (checked, with a readable error).
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import signal
import subprocess
import time

from .validate import ExplainerError

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "tools", "remotion"))
BASE_W, BASE_H = 1920, 1080
GRACE_S = 8.0
_NOWIN = getattr(subprocess, "CREATE_NO_WINDOW", 0)


def cache_dir(project_folder: str) -> str:
    return os.path.join(project_folder, "out", "remotion")


# ---- component parameter checks -------------------------------------------------

def _pos(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool) and v > 0


def _check_fit_chart(p: dict, where: str) -> list:
    errs = []
    if not _pos(p.get("limit")):
        errs.append(f"{where}: limit must be a number greater than 0.")
    if not _pos(p.get("bits")):
        errs.append(f"{where}: bits must be a number greater than 0.")
    if not isinstance(p.get("unit", "GB"), str):
        errs.append(f"{where}: unit must be text.")
    items = p.get("items")
    if not isinstance(items, list) or not 1 <= len(items) <= 5:
        return errs + [f"{where}: items must be a list of 1-5 models."]
    for k, it in enumerate(items, 1):
        if not isinstance(it, dict) or not isinstance(it.get("label"), str) or not it["label"].strip():
            errs.append(f"{where}: item {k} needs a label.")
            continue
        if len(it["label"]) > 14:
            errs.append(f"{where}: item {k} label {it['label']!r} is over 14 characters.")
        if not _pos(it.get("params_b")):
            errs.append(f"{where}: item {k} ({it['label']}) needs params_b > 0 (billions).")
        s = it.get("start_ms")
        if isinstance(s, bool) or not isinstance(s, int) or s < 0:
            errs.append(f"{where}: item {k} ({it['label']}) needs start_ms >= 0.")
    return errs


def _num(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _ms(v) -> bool:
    return isinstance(v, int) and not isinstance(v, bool) and v >= 0


def _check_counter(p: dict, where: str) -> list:
    errs = []
    if not _num(p.get("from")) or not _num(p.get("to")):
        errs.append(f"{where}: from and to must be numbers.")
    elif p["from"] == p["to"]:
        errs.append(f"{where}: from and to are the same number; nothing would count.")
    if not isinstance(p.get("unit", ""), str) or len(p.get("unit", "")) > 8:
        errs.append(f"{where}: unit must be short text (8 characters at most).")
    label = p.get("label", "")
    if not isinstance(label, str) or len(label) > 48:
        errs.append(f"{where}: label must be text of 48 characters at most.")
    if not _ms(p.get("start_ms")):
        errs.append(f"{where}: start_ms must be a whole number >= 0.")
    if not _ms(p.get("count_ms")) or p.get("count_ms", 0) < 300:
        errs.append(f"{where}: count_ms must be at least 300.")
    return errs


IMAGE_EXT = (".png", ".jpg", ".jpeg", ".webp")
IMAGE_MAX = 6 * 1024 * 1024


def _check_screenshot(p: dict, where: str) -> list:
    errs = []
    img = p.get("image")
    if (not isinstance(img, str) or os.path.isabs(img) or ".." in img.replace("\\", "/").split("/")
            or not img.lower().endswith(IMAGE_EXT)):
        errs.append(f"{where}: image must be a png/jpg/webp path inside the production folder "
                    "(relative, no '..').")
    box = p.get("box")
    if (not isinstance(box, list) or len(box) != 4 or not all(_num(v) for v in box)
            or box[0] < 0 or box[1] < 0 or box[2] <= 0.05 or box[3] <= 0.05
            or box[0] + box[2] > 1.0001 or box[1] + box[3] > 1.0001):
        errs.append(f"{where}: box must be [x, y, width, height] as fractions of the image, "
                    "inside it, at least 0.05 wide and tall.")
    if not _ms(p.get("start_ms")):
        errs.append(f"{where}: start_ms must be a whole number >= 0.")
    zm = p.get("zoom_ms")
    if not _ms(zm) or zm < 300:
        errs.append(f"{where}: zoom_ms must be at least 300.")
    cap = p.get("caption", "")
    if not isinstance(cap, str) or len(cap) > 60:
        errs.append(f"{where}: caption must be text of 60 characters at most.")
    return errs


COMPONENTS = {"fit_chart": _check_fit_chart, "counter": _check_counter, "screenshot": _check_screenshot}


def check_block(block, where: str) -> list:
    """Errors for a scene's `remotion` block ([] when fine)."""
    if not isinstance(block, dict) or set(block) - {"component", "params", "fade"}:
        return [f'{where}: remotion must be {{"component": ..., "params": {{...}}}}.']
    fade = block.get("fade")
    if fade is not None:
        if (not isinstance(fade, dict) or set(fade) - {"in_ms", "out_ms"}
                or not all(_ms(v) and v <= 2000 for v in fade.values())):
            return [f"{where}: fade must be {{\"in_ms\": n, \"out_ms\": n}} with each 0-2000."]
    name = block.get("component")
    if name not in COMPONENTS:
        return [f"{where}: unknown Remotion component {name!r} (known: {', '.join(sorted(COMPONENTS))})."]
    params = block.get("params")
    if not isinstance(params, dict):
        return [f"{where}: remotion.params must be an object."]
    return COMPONENTS[name](params, where)


# ---- fingerprint and cache --------------------------------------------------------

def project_hash() -> str:
    """Hash of everything in tools/remotion that changes pixels (not node_modules)."""
    h = hashlib.sha256()
    for root, dirs, files in os.walk(PROJECT):
        dirs[:] = sorted(d for d in dirs if d not in ("node_modules", "out", ".cache"))
        for name in sorted(files):
            path = os.path.join(root, name)
            h.update(os.path.relpath(path, PROJECT).replace("\\", "/").encode())
            with open(path, "rb") as fh:
                h.update(fh.read())
    return h.hexdigest()


def _theme_props(doc) -> dict:
    t = doc.theme
    out = {"background": t.background}
    for key, val in (("heading", getattr(t, "heading_color", None)),
                     ("text", getattr(t, "text_color", None))):
        if val and str(val).startswith("#"):
            out[key] = val
    return out


def scene_props(compiled, doc, fps: float) -> dict:
    block = compiled.spec.remotion
    return {"component": block["component"], "params": block["params"], "fade": block.get("fade"),
            "frames": int(compiled.end_frame - compiled.start_frame), "fps": float(fps),
            "theme": _theme_props(doc)}


def _prepare_assets(props: dict, project_folder: str):
    """-> (props for the cache key, props for the renderer). A screenshot is read from the
    production folder, checked, hashed for the key and inlined as a data URI for the run."""
    img = props["params"].get("image") if props["component"] == "screenshot" else None
    if not img:
        return props, props
    root = os.path.realpath(project_folder)
    path = os.path.realpath(os.path.join(root, img))
    if os.path.commonpath([root, path]) != root or not os.path.isfile(path):
        raise ExplainerError([f"Remotion screenshot {img!r} was not found inside the production folder."])
    size = os.path.getsize(path)
    if size > IMAGE_MAX:
        raise ExplainerError([f"Remotion screenshot {img!r} is {size // 1024 // 1024} MB; "
                              f"the limit is {IMAGE_MAX // 1024 // 1024} MB."])
    with open(path, "rb") as fh:
        data = fh.read()
    import base64
    mime = "image/png" if path.lower().endswith(".png") else (
        "image/webp" if path.lower().endswith(".webp") else "image/jpeg")
    keyed = json.loads(json.dumps(props))
    keyed["params"]["image"] = {"path": img, "sha": hashlib.sha256(data).hexdigest()}
    run = json.loads(json.dumps(props))
    run["params"]["image"] = f"data:{mime};base64," + base64.b64encode(data).decode()
    return keyed, run


def fingerprint(props: dict, width: int, height: int, pjhash: str = None) -> str:
    payload = json.dumps({"v": 3, "props": props, "w": width, "h": height,
                          "project": pjhash or project_hash()},
                         sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode()).hexdigest()[:16]


def scale_for(width: int, height: int) -> float:
    for s in (1.0, 0.5):
        if (width, height) == (round(BASE_W * s), round(BASE_H * s)):
            return s
    raise ExplainerError([f"Remotion scenes render at {BASE_W}x{BASE_H} or {BASE_W // 2}x{BASE_H // 2} "
                          f"(got {width}x{height})."])


# ---- running node -------------------------------------------------------------------

def node_command() -> list:
    node = shutil.which("node")
    if not node:
        raise ExplainerError(["Remotion scenes need Node.js (node was not found on PATH)."])
    if not os.path.isdir(os.path.join(PROJECT, "node_modules", "remotion")):
        raise ExplainerError([f"Remotion is not installed: run `npm ci` in {PROJECT} once."])
    return [node, os.path.join(PROJECT, "render.mjs")]


def _stop(proc) -> None:
    """Ask the owned process group to stop, then kill it. Never touches other processes."""
    if proc.poll() is not None:
        return
    try:
        if os.name == "nt":
            proc.send_signal(getattr(signal, "CTRL_BREAK_EVENT", signal.SIGTERM))
        else:
            os.killpg(proc.pid, signal.SIGTERM)
    except (OSError, ValueError):
        proc.terminate()
    deadline = time.time() + GRACE_S
    while proc.poll() is None and time.time() < deadline:
        time.sleep(0.1)
    if proc.poll() is None:
        if os.name == "nt":
            subprocess.run(["taskkill", "/PID", str(proc.pid), "/T", "/F"], capture_output=True,
                           creationflags=_NOWIN)
        else:
            try:
                os.killpg(proc.pid, signal.SIGKILL)
            except OSError:
                proc.kill()
        proc.wait()


def run(cmd: list, cancel_event=None, poll_s: float = 0.2) -> int:
    kw = {"stdout": subprocess.PIPE, "stderr": subprocess.STDOUT, "text": True}
    if os.name == "nt":
        kw["creationflags"] = _NOWIN | subprocess.CREATE_NEW_PROCESS_GROUP
    else:
        kw["start_new_session"] = True
    proc = subprocess.Popen(cmd, **kw)
    out = []
    import threading
    t = threading.Thread(target=lambda: out.append(proc.stdout.read()), daemon=True)
    t.start()
    try:
        _wait(proc, out, t, cancel_event, poll_s)
    finally:
        try:
            proc.stdout.close()
        except OSError:
            pass
    return 0


def _wait(proc, out, t, cancel_event, poll_s):
    while proc.poll() is None:
        if cancel_event is not None and cancel_event.is_set():
            _stop(proc)
            t.join(2)
            raise RuntimeError("Render cancelled.")
        time.sleep(poll_s)
    t.join(5)
    if proc.returncode != 0:
        tail = "".join(out)[-1500:]
        raise RuntimeError(f"Remotion render failed (exit {proc.returncode}): {tail}")


TIMESCALE = 15360        # the pen renderer's clips use this; the concat join needs them to match


def _retime(ffmpeg_path: str, src: str, dst: str) -> None:
    """Make the clip match the pen renderer's: same timescale (mixed timebases make concat
    repeat frames) and limited-range yuv420p (Remotion writes full-range, which the join
    would otherwise apply to the pen clips and lift their blacks)."""
    r = subprocess.run([ffmpeg_path, "-hide_banner", "-loglevel", "error", "-y", "-i", src, "-an",
                        "-vf", "scale=in_range=pc:out_range=tv,format=yuv420p",
                        "-c:v", "libx264", "-preset", "veryfast", "-crf", "16", "-bf", "0",
                        "-pix_fmt", "yuv420p", "-video_track_timescale", str(TIMESCALE), dst],
                       capture_output=True, text=True, creationflags=_NOWIN)
    if r.returncode != 0:
        raise RuntimeError(f"could not retime the Remotion clip: {r.stderr[-600:]}")


def render_scene_clip(doc, compiled, project_folder: str, fps: float, cancel_event=None,
                      canvas: tuple = None, command=None, ffmpeg_path: str = None) -> str:
    """Render one Remotion scene to out/remotion/<id>_<fingerprint>.mp4 (cached)."""
    width, height = canvas or doc.canvas
    scale = scale_for(width, height)
    props, run_props = _prepare_assets(scene_props(compiled, doc, fps), project_folder)
    fp = fingerprint(props, width, height)
    out_dir = cache_dir(project_folder)
    os.makedirs(out_dir, exist_ok=True)
    final = os.path.join(out_dir, f"{compiled.spec.id}_{fp}.mp4")
    if os.path.isfile(final):
        return final
    cmd = command or node_command()
    props_path = os.path.join(out_dir, f".props_{compiled.spec.id}_{fp}.json")
    temp = os.path.join(out_dir, f".tmp_{compiled.spec.id}_{fp}.mp4")
    with open(props_path, "w", encoding="utf-8") as fh:
        json.dump(run_props, fh)
    for stale in (temp,):
        if os.path.exists(stale):
            os.remove(stale)
    try:
        run(list(cmd) + ["--props", props_path, "--out", temp, "--scale", str(scale)], cancel_event)
        if not os.path.isfile(temp):
            raise RuntimeError("Remotion finished without writing a clip.")
        if ffmpeg_path:
            fixed = temp + ".fixed.mp4"
            try:
                _retime(ffmpeg_path, temp, fixed)
                os.replace(fixed, final)
            finally:
                if os.path.exists(fixed):
                    os.remove(fixed)
        else:
            os.replace(temp, final)
    finally:
        for p in (props_path, temp):
            try:
                os.remove(p)
            except OSError:
                pass
    return final
