PROJECT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "tools", "remotion"))
BASE_W, BASE_H = 1920, 1080
GRACE_S = 8.0
_NOWIN = getattr(subprocess, "CREATE_NO_WINDOW", 0)


def cache_dir(project_folder: str) -> str:
    return os.path.join(project_folder, "out", "remotion")


# ---- component parameter checks -------------------------------------------------

def _pos(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool) and v > 0


def _check_fit_chart(p: dict, where: str) -> list:
    errs = []
    if not _pos(p.get("limit")):
        errs.append(f"{where}: limit must be a number greater than 0.")
    if not _pos(p.get("bits")):
        errs.append(f"{where}: bits must be a number greater than 0.")
    if not isinstance(p.get("unit", "GB"), str):
        errs.append(f"{where}: unit must be text.")
    items = p.get("items")
    if not isinstance(items, list) or not 1 <= len(items) <= 5:
        return errs + [f"{where}: items must be a list of 1-5 models."]
    for k, it in enumerate(items, 1):
        if not isinstance(it, dict) or not isinstance(it.get("label"), str) or not it["label"].strip():
            errs.append(f"{where}: item {k} needs a label.")
            continue
        if len(it["label"]) > 14:
            errs.append(f"{where}: item {k} label {it['label']!r} is over 14 characters.")
        if not _pos(it.get("params_b")):
            errs.append(f"{where}: item {k} ({it['label']}) needs params_b > 0 (billions).")
        s = it.get("start_ms")
        if isinstance(s, bool) or not isinstance(s, int) or s < 0:
            errs.append(f"{where}: item {k} ({it['label']}) needs start_ms >= 0.")
    return errs


def _num(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _ms(v) -> bool:
    return isinstance(v, int) and not isinstance(v, bool) and v >= 0


def _check_counter(p: dict, where: str) -> list:
    errs = []
    if not _num(p.get("from")) or not _num(p.get("to")):
        errs.append(f"{where}: from and to must be numbers.")
    elif p["from"] == p["to"]:
        errs.append(f"{where}: from and to are the same number; nothing would count.")
    if not isinstance(p.get("unit", ""), str) or len(p.get("unit", "")) > 8:
        errs.append(f"{where}: unit must be short text (8 characters at most).")
    label = p.get("label", "")
    if not isinstance(label, str) or len(label) > 48:
        errs.append(f"{where}: label must be text of 48 characters at most.")
    if not _ms(p.get("start_ms")):
        errs.append(f"{where}: start_ms must be a whole number >= 0.")
    if not _ms(p.get("count_ms")) or p.get("count_ms", 0) < 300:
        errs.append(f"{where}: count_ms must be at least 300.")
    return errs


IMAGE_EXT = (".png", ".jpg", ".jpeg", ".webp")
IMAGE_MAX = 6 * 1024 * 1024


def _check_screenshot(p: dict, where: str) -> list:
    errs = []
    img = p.get("image")
    if (not isinstance(img, str) or os.path.isabs(img) or ".." in img.replace("\\", "/").split("/")
            or not img.lower().endswith(IMAGE_EXT)):
        errs.append(f"{where}: image must be a png/jpg/webp path inside the production folder "
                    "(relative, no '..').")
    box = p.get("box")
    if (not isinstance(box, list) or len(box) != 4 or not all(_num(v) for v in box)
            or box[0] < 0 or box[1] < 0 or box[2] <= 0.05 or box[3] <= 0.05
            or box[0] + box[2] > 1.0001 or box[1] + box[3] > 1.0001):
        errs.append(f"{where}: box must be [x, y, width, height] as fractions of the image, "
                    "inside it, at least 0.05 wide and tall.")
    if not _ms(p.get("start_ms")):
        errs.append(f"{where}: start_ms must be a whole number >= 0.")
    zm = p.get("zoom_ms")
    if not _ms(zm) or zm < 300:
        errs.append(f"{where}: zoom_ms must be at least 300.")
    cap = p.get("caption", "")
    if not isinstance(cap, str) or len(cap) > 60:
        errs.append(f"{where}: caption must be text of 60 characters at most.")
    return errs


def _text(v, n) -> bool:
    return isinstance(v, str) and 0 < len(v.strip()) <= n


def _check_pipeline(p: dict, where: str) -> list:
    errs = []
    st = p.get("stages")
    if not isinstance(st, list) or not 2 <= len(st) <= 8:
        return [f"{where}: stages must be a list of 2-8 stages."]
    for k, x in enumerate(st, 1):
        if not isinstance(x, dict) or not _text(x.get("label"), 22 if len(st) <= 3 else 14):
            errs.append(f"{where}: stage {k} needs a label of {22 if len(st) <= 3 else 14} characters at most.")
            continue
        if not isinstance(x.get("workers"), int) or isinstance(x.get("workers"), bool) or not 1 <= x["workers"] <= 8:
            errs.append(f"{where}: stage {k} workers must be a whole number 1-8.")
        if "at_ms" in x and not _ms(x["at_ms"]):
            errs.append(f"{where}: stage {k} at_ms must be a whole number >= 0.")
        if "work" in x and (not _pos(x["work"]) or x["work"] > 10):
            errs.append(f"{where}: stage {k} work must be a number 0-10 (relative time per task).")
    if not isinstance(p.get("tasks"), int) or isinstance(p.get("tasks"), bool) or not 4 <= p["tasks"] <= 24:
        errs.append(f"{where}: tasks must be a whole number 4-24.")
    if not _ms(p.get("start_ms")) or not _ms(p.get("run_ms")) or p.get("run_ms", 0) < 3000:
        errs.append(f"{where}: start_ms >= 0 and run_ms >= 3000 are needed.")
    for key, n in (("title", 48), ("sub", 70), ("note", 70)):
        if key in p and not isinstance(p[key], str) or len(p.get(key) or "") > n:
            errs.append(f"{where}: {key} must be text of {n} characters at most.")
    return errs


GEN_MODES = ("sequential", "plan_then_fill")


def _check_footer(p: dict, where: str) -> list:
    f = p.get("footer")
    if f is None:
        return []
    if not isinstance(f, dict) or not _text(f.get("text"), 70) or not _ms(f.get("start_ms")):
        return [f"{where}: footer must be text of 70 characters at most."]
    return []


def _check_generation(p: dict, where: str) -> list:
    errs = []
    rows = p.get("rows")
    if not isinstance(rows, list) or not 1 <= len(rows) <= 2:
        return [f"{where}: rows must be a list of 1-2 rows."]
    for k, r in enumerate(rows, 1):
        if not isinstance(r, dict) or not _text(r.get("label"), 34):
            errs.append(f"{where}: row {k} needs a label of 34 characters at most.")
            continue
        if r.get("mode") not in GEN_MODES:
            errs.append(f"{where}: row {k} mode must be one of {', '.join(GEN_MODES)}.")
        w = r.get("words")
        if (not isinstance(w, list) or not 4 <= len(w) <= 14 or not all(_text(x, 18) for x in w)):
            errs.append(f"{where}: row {k} words must be 4-14 short words (18 characters at most).")
        elif any(not any(ch.isalnum() for ch in x) for x in w):
            errs.append(f"{where}: row {k} words must all be real text; a blank like '___' never gets filled in. "
                        "Write the final word for every slot (the animation shows each one empty until its step).")
        bm = r.get("beats_ms")
        if bm is not None and (not isinstance(bm, list) or not 1 <= len(bm) <= 3 or not all(_ms(v) for v in bm)
                               or sorted(bm) != bm):
            errs.append(f"{where}: row {k} beats must be 1-3 narration anchors in the order they are said.")
    if not _ms(p.get("start_ms")) or not _ms(p.get("run_ms")) or p.get("run_ms", 0) < 3000:
        errs.append(f"{where}: start_ms >= 0 and run_ms >= 3000 are needed.")
    for key, n in (("title", 48), ("sub", 70), ("note", 70)):
        if key in p and not isinstance(p[key], str) or len(p.get(key) or "") > n:
            errs.append(f"{where}: {key} must be text of {n} characters at most.")
    return errs


LEVEL_CELLS = (1, 16)


def _check_levels(p: dict, where: str) -> list:
    errs = []
    lv = p.get("levels")
    if not isinstance(lv, list) or not 2 <= len(lv) <= 4:
        return [f"{where}: levels must be a list of 2-4 levels (broad first)."]
    last = 0
    for k, x in enumerate(lv, 1):
        if (not isinstance(x, dict) or not _text(x.get("label"), 28) or not isinstance(x.get("cells"), int)
                or isinstance(x.get("cells"), bool) or not LEVEL_CELLS[0] <= x["cells"] <= LEVEL_CELLS[1]
                or not _ms(x.get("at_ms"))):
            errs.append(f"{where}: level {k} needs a label (28 characters) and cells 1-16.")
            continue
        if x["cells"] < last:
            errs.append(f"{where}: level {k} has fewer cells than the level before; finer levels have more.")
        last = x["cells"]
    for key in ("decoder", "result"):
        d = p.get(key)
        if d is not None and (not isinstance(d, dict) or not _text(d.get("label" if key == "decoder" else "text"), 60)
                              or not _ms(d.get("at_ms"))):
            errs.append(f"{where}: {key} needs {'a label' if key == 'decoder' else 'text'} of 60 characters at most.")
    if not _ms(p.get("start_ms")):
        errs.append(f"{where}: start_ms must be a whole number >= 0.")
    return errs


def _check_code(p: dict, where: str) -> list:
    errs = []
    ln = p.get("lines")
    if not isinstance(ln, list) or not 2 <= len(ln) <= 12 or not all(isinstance(x, str) and len(x) <= 64 for x in ln):
        errs.append(f"{where}: lines must be 2-12 lines of 64 characters at most.")
        ln = []
    if not _text(p.get("filename"), 40):
        errs.append(f"{where}: filename must be short text.")
    if not _ms(p.get("start_ms")) or not _ms(p.get("type_ms")) or p.get("type_ms", 0) < 800:
        errs.append(f"{where}: start_ms >= 0 and type_ms >= 800 are needed.")
    for h in p.get("highlights") or []:
        if (not isinstance(h, dict) or not isinstance(h.get("line"), int) or not 1 <= h["line"] <= max(len(ln), 1)
                or not _ms(h.get("start_ms")) or len(str(h.get("note", ""))) > 40):
            errs.append(f"{where}: each highlight needs line (1-{len(ln)}), start_ms and an optional note (40 characters).")
            break
    for key, n in (("title", 48), ("sub", 70)):
        if key in p and not isinstance(p[key], str) or len(p.get(key) or "") > n:
            errs.append(f"{where}: {key} must be text of {n} characters at most.")
    return errs


COMPONENTS = {"fit_chart": _check_fit_chart, "counter": _check_counter, "screenshot": _check_screenshot,
              "pipeline": _check_pipeline, "generation": _check_generation, "code": _check_code,
              "levels": _check_levels}

# Motion style presets are data: a channel picks a preset and may override colours.
STYLE_PRESETS = ("tech", "warm", "light")


def check_style(style, where: str) -> list:
    if style is None:
        return []
    if not isinstance(style, dict) or set(style) - {"preset", "colors"}:
        return [f'{where}: motion_style must be {{"preset": ..., "colors": {{...}}}}.']
    if style.get("preset") not in (None,) + STYLE_PRESETS:
        return [f"{where}: motion_style preset must be one of {', '.join(STYLE_PRESETS)}."]
    cols = style.get("colors") or {}
    ok = ("accent", "accent2", "good", "bad", "panel", "line", "text", "dim", "bg2")
    import re
    if not isinstance(cols, dict) or any(k not in ok or not re.fullmatch(r"#[0-9a-fA-F]{6}", str(v)) for k, v in cols.items()):
        return [f"{where}: motion_style colors must be #rrggbb values for {', '.join(ok)}."]
    return []


def check_block(block, where: str) -> list:
    """Errors for a scene's `remotion` block ([] when fine)."""
    if not isinstance(block, dict) or set(block) - {"component", "params", "fade", "style"}:
        return [f'{where}: remotion must be {{"component": ..., "params": {{...}}}}.']
    fade = block.get("fade")
    if fade is not None:
        if (not isinstance(fade, dict) or set(fade) - {"in_ms", "out_ms"}
                or not all(_ms(v) and v <= 2000 for v in fade.values())):
            return [f"{where}: fade must be {{\"in_ms\": n, \"out_ms\": n}} with each 0-2000."]
    bad = check_style(block.get("style"), where)
    if bad:
        return bad
    name = block.get("component")
    if name not in COMPONENTS:
        return [f"{where}: unknown Remotion component {name!r} (known: {', '.join(sorted(COMPONENTS))})."]
    params = block.get("params")
    if not isinstance(params, dict):
        return [f"{where}: remotion.params must be an object."]
    return COMPONENTS[name](params, where) + _check_footer(params, where)


# ---- fingerprint and cache --------------------------------------------------------

def project_hash() -> str:
    """Hash of everything in tools/remotion that changes pixels (not node_modules)."""
    h = hashlib.sha256()
    for root, dirs, files in os.walk(PROJECT):
        dirs[:] = sorted(d for d in dirs if d not in ("node_modules", "out", ".cache"))
        for name in sorted(files):
            path = os.path.join(root, name)
            h.update(os.path.relpath(path, PROJECT).replace("\\", "/").encode())
            with open(path, "rb") as fh:
                h.update(fh.read())
    return h.hexdigest()


def _theme_props(doc) -> dict:
    """The channel's look, read from the theme: colours, which fonts, hand-drawn or graphic.
    Nothing about a channel is decided inside the Remotion components."""
    t = doc.theme

    def colour(v):
        return v if v and str(v).startswith("#") else None
    out = {"background": t.background}
    for key, val in (("heading", colour(getattr(t, "heading_color", None))),
                     ("text", colour(getattr(t, "text_color", None)))):
        if val:
            out[key] = val
    look = {"bg": t.background, "fg": t.foreground, "muted": t.muted, "accent": t.accent,
            "good": t.positive, "bad": t.negative}
    for key, val in (("heading", out.get("heading")), ("text", out.get("text"))):
        if val:
            look[key] = val
    out["look"] = look
    out["hand"] = getattr(t, "line_style", "") != "straight"      # straight = graphic channel
    out["font_files"] = {"heading": t.heading_font, "body": t.body_font,
                         "note": (t.hand_font if out["hand"] and t.hand_font else t.body_font),
                         "mono": t.mono_font}
    return out


def scene_props(compiled, doc, fps: float) -> dict:
    block = compiled.spec.remotion
    theme = _theme_props(doc)
    st = block.get("style") or {}
    if st.get("colors"):
        theme["look"].update({k: v for k, v in st["colors"].items() if k in ("accent", "good", "bad")})
        if st["colors"].get("text"):
            theme["look"]["text"] = st["colors"]["text"]
        if st["colors"].get("accent2"):
            theme["look"]["heading"] = st["colors"]["accent2"]
    return {"component": block["component"], "params": block["params"], "fade": block.get("fade"),
            "frames": int(compiled.end_frame - compiled.start_frame), "fps": float(fps),
            "theme": theme}


FONT_MAX = 3 * 1024 * 1024


def _fonts(props: dict, project_folder: str):
    """-> (keyed, run): theme.font_files names are resolved to files, hashed for the cache key
    and inlined as data URIs for the run. A font that cannot be found is skipped (the
    components fall back to a clean system font), never an error."""
    import base64
    from .layout import find_font
    files = props["theme"].pop("font_files", {}) or {}
    keyed, run, names = {}, {}, {}
    for role, name in files.items():
        if not name:
            continue
        path = find_font(name, project_folder)
        if not path or not os.path.isfile(path) or os.path.getsize(path) > FONT_MAX:
            continue
        with open(path, "rb") as fh:
            data = fh.read()
        fam = "WR" + role.capitalize()
        names[role] = fam
        keyed[fam] = {"file": os.path.basename(path), "sha": hashlib.sha256(data).hexdigest()}
        mime = "font/otf" if path.lower().endswith(".otf") else "font/ttf"
        run[fam] = f"data:{mime};base64," + base64.b64encode(data).decode()
    props["theme"]["fonts"] = names
    return keyed, run


def _prepare_assets(props: dict, project_folder: str):
    """-> (props for the cache key, props for the renderer). A screenshot is read from the
    production folder, checked, hashed for the key and inlined as a data URI for the run."""
    props = json.loads(json.dumps(props))
    fkey, frun = _fonts(props, project_folder)
    img = props["params"].get("image") if props["component"] == "screenshot" else None
    if not img:
        keyed = json.loads(json.dumps(props))
        keyed["theme"]["fontData"] = fkey
        run = json.loads(json.dumps(props))
        run["theme"]["fontData"] = frun
        return keyed, run
    root = os.path.realpath(project_folder)
    path = os.path.realpath(os.path.join(root, img))
    if os.path.commonpath([root, path]) != root or not os.path.isfile(path):
        raise ExplainerError([f"Remotion screenshot {img!r} was not found inside the production folder."])
    size = os.path.getsize(path)
    if size > IMAGE_MAX:
        raise ExplainerError([f"Remotion screenshot {img!r} is {size // 1024 // 1024} MB; "
                              f"the limit is {IMAGE_MAX // 1024 // 1024} MB."])
    with open(path, "rb") as fh:
        data = fh.read()
    import base64
    mime = "image/png" if path.lower().endswith(".png") else (
        "image/webp" if path.lower().endswith(".webp") else "image/jpeg")
    keyed = json.loads(json.dumps(props))
    keyed["params"]["image"] = {"path": img, "sha": hashlib.sha256(data).hexdigest()}
    keyed["theme"]["fontData"] = fkey
    run = json.loads(json.dumps(props))
    run["theme"]["fontData"] = frun
    run["params"]["image"] = f"data:{mime};base64," + base64.b64encode(data).decode()
    return keyed, run


def fingerprint(props: dict, width: int, height: int, pjhash: str = None) -> str:
    payload = json.dumps({"v": 3, "props": props, "w": width, "h": height,
                          "project": pjhash or project_hash()},
                         sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode()).hexdigest()[:16]


def scale_for(width: int, height: int) -> float:
    for s in (1.0, 0.5):
        if (width, height) == (round(BASE_W * s), round(BASE_H * s)):
            return s
    raise ExplainerError([f"Remotion scenes render at {BASE_W}x{BASE_H} or {BASE_W // 2}x{BASE_H // 2} "
                          f"(got {width}x{height})."])


# ---- running node -------------------------------------------------------------------

def node_command() -> list:
    node = shutil.which("node")
    if not node:
        raise ExplainerError(["Remotion scenes need Node.js (node was not found on PATH)."])
    if not os.path.isdir(os.path.join(PROJECT, "node_modules", "remotion")):
        raise ExplainerError([f"Remotion is not installed: run `npm ci` in {PROJECT} once."])
    return [node, os.path.join(PROJECT, "render.mjs")]


def _stop(proc) -> None:
    """Ask the owned process group to stop, then kill it. Never touches other processes."""
    if proc.poll() is not None:
        return
    try:
        if os.name == "nt":
            proc.send_signal(getattr(signal, "CTRL_BREAK_EVENT", signal.SIGTERM))
        else:
            os.killpg(proc.pid, signal.SIGTERM)
    except (OSError, ValueError):
        proc.terminate()
    deadline = time.time() + GRACE_S
    while proc.poll() is None and time.time() < deadline:
        time.sleep(0.1)
    if proc.poll() is None:
        if os.name == "nt":
            try:
                subprocess.run(["taskkill", "/PID", str(proc.pid), "/T", "/F"], capture_output=True,
                               creationflags=_NOWIN, timeout=3)
            except (OSError, subprocess.TimeoutExpired):
                pass
            # Sandboxed Windows sessions may deny taskkill. Never wait forever
            # for an owned renderer after the tree-kill attempt failed.
            if proc.poll() is None:
                proc.kill()
        else:
            try:
                os.killpg(proc.pid, signal.SIGKILL)
            except OSError:
                proc.kill()
        try:
            proc.wait(timeout=2)
        except subprocess.TimeoutExpired as exc:
            raise RuntimeError("The owned renderer did not stop after cancellation.") from exc


def run(cmd: list, cancel_event=None, poll_s: float = 0.2) -> int:
    kw = {"stdout": subprocess.PIPE, "stderr": subprocess.STDOUT, "text": True}
    if os.name == "nt":
        kw["creationflags"] = _NOWIN | subprocess.CREATE_NEW_PROCESS_GROUP
    else:
        kw["start_new_session"] = True
    proc = subprocess.Popen(cmd, **kw)
    out = []
    import threading
    t = threading.Thread(target=lambda: out.append(proc.stdout.read()), daemon=True)
    t.start()
    try:
        _wait(proc, out, t, cancel_event, poll_s)
    finally:
        try:
            proc.stdout.close()
        except OSError:
            pass
    return 0


def _wait(proc, out, t, cancel_event, poll_s):
    while proc.poll() is None:
        if cancel_event is not None and cancel_event.is_set():
            _stop(proc)
            t.join(2)
            raise RuntimeError("Render cancelled.")
        time.sleep(poll_s)
    t.join(5)
    if proc.returncode != 0:
        tail = "".join(out)[-1500:]
        raise RuntimeError(f"Remotion render failed (exit {proc.returncode}): {tail}")


TIMESCALE = 15360        # the pen renderer's clips use this; the concat join needs them to match


def _retime(ffmpeg_path: str, src: str, dst: str) -> None:
    """Make the clip match the pen renderer's: same timescale (mixed timebases make concat
    repeat frames) and limited-range yuv420p (Remotion writes full-range, which the join
    would otherwise apply to the pen clips and lift their blacks)."""
    r = subprocess.run([ffmpeg_path, "-hide_banner", "-loglevel", "error", "-y", "-i", src, "-an",
                        "-vf", "scale=in_range=pc:out_range=tv,format=yuv420p",
                        "-c:v", "libx264", "-preset", "veryfast", "-crf", "16", "-bf", "0",
                        "-pix_fmt", "yuv420p", "-video_track_timescale", str(TIMESCALE), dst],
                       capture_output=True, text=True, creationflags=_NOWIN)
    if r.returncode != 0:
        raise RuntimeError(f"could not retime the Remotion clip: {r.stderr[-600:]}")


def render_scene_clip(doc, compiled, project_folder: str, fps: float, cancel_event=None,
                      canvas: tuple = None, command=None, ffmpeg_path: str = None) -> str:
    """Render one Remotion scene to out/remotion/<id>_<fingerprint>.mp4 (cached)."""
    width, height = canvas or doc.canvas
    scale = scale_for(width, height)
    props, run_props = _prepare_assets(scene_props(compiled, doc, fps), project_folder)
    fp = fingerprint(props, width, height)
    out_dir = cache_dir(project_folder)
    os.makedirs(out_dir, exist_ok=True)
    final = os.path.join(out_dir, f"{compiled.spec.id}_{fp}.mp4")
    if os.path.isfile(final):
        return final
    cmd = command or node_command()
    props_path = os.path.join(out_dir, f".props_{compiled.spec.id}_{fp}.json")
    temp = os.path.join(out_dir, f".tmp_{compiled.spec.id}_{fp}.mp4")
    with open(props_path, "w", encoding="utf-8") as fh:
        json.dump(run_props, fh)
    for stale in (temp,):
        if os.path.exists(stale):
            os.remove(stale)
    try:
        run(list(cmd) + ["--props", props_path, "--out", temp, "--scale", str(scale)], cancel_event)
        if not os.path.isfile(temp):
            raise RuntimeError("Remotion finished without writing a clip.")
        if ffmpeg_path:
            fixed = temp + ".fixed.mp4"
            try:
                _retime(ffmpeg_path, temp, fixed)
                os.replace(fixed, final)
            finally:
                if os.path.exists(fixed):
                    os.remove(fixed)
        else:
            os.replace(temp, final)
    finally:
        for p in (props_path, temp):
            try:
                os.remove(p)
            except OSError:
                pass
    return final
